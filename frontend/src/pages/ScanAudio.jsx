import React, { useEffect, useMemo, useState } from 'react';
import AppShell from '../components/AppShell';
import Icon from '../components/Icons';
import Dropzone from '../components/Dropzone';
import { Callout, PageHeader, ResultView, ScanWorkspace } from '../components/ui';
import api from '../api/api';

export default function ScanAudio() {
  const [file, setFile] = useState(null);
  const [result, setResult] = useState(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const audioUrl = useMemo(() => (file ? URL.createObjectURL(file) : null), [file]);
  useEffect(() => () => { if (audioUrl) URL.revokeObjectURL(audioUrl); }, [audioUrl]);

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!file) return;
    setBusy(true); setError(''); setResult(null);
    try {
      const formData = new FormData();
      formData.append('audio', file);
      const { data } = await api.post('/scan/audio', formData, { headers: { 'Content-Type': 'multipart/form-data' }, timeout: 180000 });
      setResult(data);
    } catch (err) {
      setError(err.response?.data?.error || 'Scan failed. Check that the backend is running.');
    } finally {
      setBusy(false);
    }
  };

  const form = (
    <div className="cg-panel">
      <form onSubmit={handleSubmit}>
        <div className="cg-panel-title">Voice clip</div>
        <Dropzone accept="audio/*,.wav,.mp3,.m4a,.ogg,.opus,.webm" file={file} onFile={(f) => { setFile(f); setResult(null); setError(''); }}
          hint="WAV, MP3, M4A, OGG (WhatsApp voice notes) up to 100 MB" maxBytes={100 * 1024 * 1024} />
        {audioUrl && <audio controls src={audioUrl} style={{ width: '100%', marginTop: 14 }} />}
        <button type="submit" className="cg-btn-primary w-100" style={{ marginTop: 16 }} disabled={busy || !file}>
          {busy ? <><span className="cg-spinner" />Analysing…</> : <><Icon name="search" />Analyse voice</>}
        </button>
        {error && <div className="cg-error"><Icon name="alert" size={16} />{error}</div>}
      </form>
    </div>
  );

  return (
    <AppShell>
      <PageHeader eyebrow="Detect · Voice cloning" title="Voice & audio scan" art="audio"
        subtitle="Check whether a voice note or call recording was generated by text-to-speech or a voice-cloning tool." />
      <ScanWorkspace
        form={form} busy={busy}
        emptyHints={['Scored in 2-second windows', 'MFCC and spectral features (41 per window)', 'Short fake segments are not diluted', 'Gemini audio reasoning when online']}
        result={result && (
          <ResultView
            result={result}
            chips={result.authenticityScore != null ? <span className="cg-chip">Authenticity {result.authenticityScore}/100</span> : null}
            summaryExtra={!result.geminiConfigured && <Callout tone="warn" icon="cloudOff">AI audio check unavailable (offline or no Gemini key): signal forensics and the ML model only.</Callout>}
            ml={{ title: 'ML synthetic-voice detector (C++ Gradient Boosted Trees on MFCC)', label: 'likely synthetic / cloned voice' }}
          />
        )}
      />
    </AppShell>
  );
}
